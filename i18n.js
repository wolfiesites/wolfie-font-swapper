  function browserLang() {
    let ui = "en";
    try {
      ui = chrome.i18n.getUILanguage() || "en";
    } catch (e) {
      ui = (navigator.language || "en");
    }
    const two = ui.toLowerCase().slice(0, 2);
    return SUPPORTED.includes(two) ? two : "en";
  }

  function currentLang() {
    let pref = null;
    try {
      pref = localStorage.getItem("wfs_lang");
    } catch (e) {
      /* localStorage niedostępny */
    }
    if (pref && SUPPORTED.includes(pref)) return pref;
    return browserLang();
  }

  function t(key) {
    const lang = currentLang();
    return (DICT[lang] && DICT[lang][key]) || DICT.en[key] || key;
  }

  function applyI18n(root) {
    const r = root || document;
    r.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    r.querySelectorAll("[data-i18n-ph]").forEach((el) => {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph")));
    });
    r.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
    });
  }

  function setLang(code) {
    try {
      if (code) localStorage.setItem("wfs_lang", code);
      else localStorage.removeItem("wfs_lang");
    } catch (e) {
      /* ignore */
    }
  }

  window.WOLFIE_I18N = {
    t,
    applyI18n,
    setLang,
    currentLang,
    browserLang,
    SUPPORTED,
    LANG_NAMES,
  };
